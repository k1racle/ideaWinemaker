const parsePolicySections = (source: string): PolicySection[] => {
  const lines = source.replace(/\r\n/g, '\n').split('\n')
  const headingIndexes = lines.flatMap((line, index) => {
    const title = line.trim()
    const previousLine = lines[index - 1]?.trim() || ''
    if (!title || previousLine || !line.startsWith('    ') || /[;:]$/.test(title)) return []

    const nextLine = lines.slice(index + 1).find(item => item.trim())?.trim() || ''
    const isHeading = /^\d+\.\d+\./.test(nextLine) || title === 'Контакты Оператора'
    return isHeading ? [index] : []
  })

  return headingIndexes.map((headingIndex, index) => {
    const nextHeadingIndex = headingIndexes[index + 1] ?? lines.length
    const content = lines.slice(headingIndex + 1, nextHeadingIndex).join('\n').trim()

    return {
      title: lines[headingIndex]?.trim() || '',
      paragraphs: content ? [content] : [],
    }
  })
}

